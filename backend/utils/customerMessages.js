const sendBookingInvoice = async (booking) => {
  const to = clean(booking.customerEmail || booking.userEmail);
  if (booking.invoiceSentAt) return;
  if (!to) {
    const err = new Error('No customer email on booking for confirmation email');
    err.code = 'INVALID_RECIPIENT';
    throw err;
  }
  const isCab = booking.bookingType === 'cab' || booking.service_billing_model === 'taxi_direct';
  const isTour = booking.bookingType === 'tour' || booking.service_billing_model === 'tour_direct';
  const hotelBooking = isHotelMarketplace(booking);
  const documentTitle = isCab
    ? 'CAB BOOKING CONFIRMATION'
    : isTour
    ? 'PILGRIMAGE TOUR CONFIRMATION'
    : hotelBooking
    ? 'BOOKING CONFIRMATION & PAYMENT RECEIPT'
    : 'TAX INVOICE';
  const emailSubject = isCab
    ? `Vrindavan Sarthi cab booking confirmation ${booking.bookingId}`
    : isTour
    ? `Vrindavan Sarthi tour booking confirmation ${booking.bookingId}`
    : hotelBooking
    ? `Vrindavan Sarthi booking confirmation ${booking.bookingId}`
    : `${COMPANY_NAME} tax invoice ${booking.bookingId}`;
  const filenamePrefix = (hotelBooking || isCab || isTour) ? 'booking-receipt' : 'tax-invoice';
  const emailIntro = isCab
    ? 'Your cab booking has been confirmed. Here are the journey, vehicle, and payment details.'
    : isTour
    ? 'Your pilgrimage tour booking has been confirmed. Here are the tour, itinerary, and payment details.'
    : hotelBooking
    ? HOTEL_MARKETPLACE_DISCLAIMER
    : 'Your payment has been verified. Here are the complete booking and payment details.';
  const rows = bookingRows(booking);
  return sendEmail({
    to,
    subject: emailSubject,
    text: [documentTitle, ...(hotelBooking ? [HOTEL_MARKETPLACE_DISCLAIMER] : []), ...rows.map(([k, v]) => `${k}: ${v}`)].join('\n'),
    html: emailShell({
      title: documentTitle,
      intro: emailIntro,
      rows,
      totalAmount: booking.totalAmount,
    }),
    attachments: [{
      filename: `${filenamePrefix}-${booking.bookingId}.pdf`,
      content: buildBookingReceiptPdf(booking).buffer,
      contentType: 'application/pdf',
    }],
  });
};

const sendOrderInvoice = async (order) => {
  const to = clean(order.userEmail);
  if (!to || order.invoiceSentAt) return;
  const rows = orderRows(order);
  return sendEmail({
    to,
    subject: `${COMPANY_NAME} order invoice ${order.orderId}`,
    text: [`${COMPANY_NAME} order invoice`, ...rows.map(([k, v]) => `${k}: ${v}`)].join('\n'),
    html: emailShell({
      title: 'TAX INVOICE',
      intro: 'Your order payment has been verified. Here are the product, delivery, and payment details.',
      rows,
      totalAmount: order.totalAmount,
    }),
    attachments: [{
      filename: `invoice-${order.orderId}.pdf`,
      content: buildPdf({
        title: 'TAX INVOICE',
        documentLabel: 'TAX INVOICE',
        sections: [{ title: 'Order Details', rows }],
        totalAmount: order.totalAmount,
      }),
      contentType: 'application/pdf',
    }],
  });
};

const sendBookingCancellationEmail = async (booking, reason) => {
  const to = clean(booking.customerEmail || booking.userEmail);
  if (!to) return;
  return sendEmail({
    to,
    subject: `Booking cancelled ${booking.bookingId}`,
    text: `Your ${COMPANY_NAME} booking ${booking.bookingId} has been cancelled.\nReason: ${reason}\nCancellation charge: ${money(booking.cancellationDeductionAmount)}\nRefundable amount: ${money(booking.refundableAmount)}`,
    html: emailShell({
      title: 'Booking cancelled',
      intro: 'Your booking has been cancelled. The reason, cancellation charge, and refundable amount are shown below.',
      rows: bookingRows(booking),
      totalLabel: 'Booking Value',
      totalAmount: booking.totalAmount,
      reason,
    }),
  });
};

const sendOrderCancellationEmail = async (order, reason) => {
  const to = clean(order.userEmail);
  if (!to) return;
  return sendEmail({
    to,
    subject: `Order cancelled ${order.orderId}`,
    text: `Your ${COMPANY_NAME} order ${order.orderId} has been cancelled.\nReason: ${reason}\nCancellation charge: ${money(order.cancellationDeductionAmount)}\nRefundable amount: ${money(order.refundableAmount)}`,
    html: emailShell({
      title: 'Order cancelled',
      intro: 'Your order has been cancelled. The reason, cancellation charge, and refundable amount are shown below.',
      rows: orderRows(order),
      totalLabel: 'Order Value',
      totalAmount: order.totalAmount,
      reason,
    }),
  });
};

const adminEmails = async () => {
  const users = await User.find({ role: 'admin' }).select('email').lean();
  return [...new Set(users.map((u) => clean(u.email)).filter(Boolean))];
};

const sendAdminAlert = async ({ subject, title, intro, rows }) => {
  const explicit = clean(process.env.ADMIN_NOTIFICATION_EMAIL);
  const recipients = explicit ? [explicit] : await adminEmails();
  const results = await Promise.allSettled(recipients.map((to) => sendEmail({ to, subject, text: [title, ...rows.map(([k, v]) => `${k}: ${v}`)].join('\n'), html: emailShell({ title, intro, rows }) })));
  return { provider: 'email', providerMessageId: results.find((result) => result.status === 'fulfilled')?.value?.providerMessageId };
};

const sendPartnerBookingAlert = async (booking) => {
  if (!booking?.partnerId) return;
  const partner = await User.findById(booking.partnerId).select('email businessEmail').lean();
  const to = clean(partner?.businessEmail || partner?.email);
  if (!to) return;
  const rows = bookingRows(booking);
  return sendEmail({
    to,
    subject: `New Vrindavan Sarthi Enterprises Booking ${booking.bookingId}`,
    text: ['New booking received', ...rows.map(([k, v]) => `${k}: ${v}`)].join('\n'),
    html: emailShell({
      title: 'New booking received',
      intro: 'A customer has submitted a booking for your property. Please review payment and booking details.',
      rows,
    }),
  });
};

const generateBookingInvoicePdf = (booking, context = {}) => {
  const receipt = buildBookingReceiptPdf(booking, context);
  return {
    buffer: receipt.buffer,
    filename: receipt.filename,
    documentTitle: receipt.documentTitle,
  };
};

